#!/usr/bin/env node
// Generates src/data/exercises-illustrated.ts from the Everkinetic dataset
// (github.com/everkinetic/data — CC BY-SA 4.0): ~290 exercises with fully
// CONSISTENT hand-drawn technique illustrations (tension + relaxation SVGs
// on jsDelivr) plus step-by-step instructions, muscles and equipment.
// Run: node scripts/generate-illustrated-exercises.mjs
import { writeFileSync } from "node:fs";

const DATA_URL = "https://raw.githubusercontent.com/everkinetic/data/main/exercises.json";
const SVG_LIST_URL = "https://api.github.com/repos/everkinetic/data/contents/dist/svg";

const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();

const [exercises, svgList] = await Promise.all([
  fetch(DATA_URL).then((r) => r.json()),
  fetch(SVG_LIST_URL).then((r) => r.json()),
]);
const svgNames = new Set(svgList.map((f) => f.name));

// Upstream defects, fixed at the source so a regeneration keeps the fix:
//  - 0020 is claimed by both "Back Fly's with Exercise Band" and "Tate Press";
//    the drawing is the standing band pull, and the lying dumbbell press already
//    exists as tate-press-with-dumbbell (0203) — the duplicate is dropped.
//  - push-up-feet-elevated ships with no type, muscles or equipment.
const DROP_SLUGS = new Set(["tate-press"]);
const OVERRIDES = {
  "push-up-feet-elevated": { type: "compound", primary: ["chest"], secondary: ["triceps", "shoulders"], equipment: ["body", "bench"] },
};

const seen = new Set();
const out = [];
for (const e of exercises) {
  if (!e.id_num || !e.title || !e.steps?.length) continue;
  if (!svgNames.has(`${e.id_num}-tension.svg`) || !svgNames.has(`${e.id_num}-relaxation.svg`)) continue;
  const slug = e.name || norm(e.title).replace(/ /g, "-");
  if (seen.has(slug) || DROP_SLUGS.has(slug)) continue;
  seen.add(slug);
  const primary = (e.primary ?? "").split(",").map((m) => m.trim()).filter(Boolean);
  const secondary = Array.isArray(e.secondary) ? e.secondary : [];
  out.push({
    slug,
    title: e.title,
    idNum: e.id_num,
    type: e.type ?? null,
    primary,
    secondary,
    equipment: Array.isArray(e.equipment) ? e.equipment : [],
    steps: e.steps,
    ...(OVERRIDES[slug] ?? {}),
  });
}
out.sort((a, b) => a.title.localeCompare(b.title));

const ts = `// AUTO-GENERATED by scripts/generate-illustrated-exercises.mjs — do not hand-edit.
// Source: github.com/everkinetic/data (CC BY-SA 4.0). ${out.length} exercises,
// each with two consistent hand-drawn technique SVGs (tension + relaxation)
// served from jsDelivr, plus step-by-step instructions.

export interface IllustratedExercise {
  slug: string; title: string; idNum: string; type: string | null;
  primary: string[]; secondary: string[]; equipment: string[]; steps: string[];
}

export const ILLUSTRATED_EXERCISES: IllustratedExercise[] = ${JSON.stringify(out)};

const CDN = "https://cdn.jsdelivr.net/gh/everkinetic/data@main/dist/svg";
/** Raw SVG (14–28KB each — used only as the onError fallback). */
export const illustrationUrl = (idNum: string, state: "tension" | "relaxation"): string =>
  \`\${CDN}/\${idNum}-\${state}.svg\`;

/** Rasterized WebP via the image proxy — ~4KB at thumb size with CDN edge
 *  caching, so lists paint fast instead of downloading + rasterizing a
 *  20KB vector per row. */
export const illustrationImg = (idNum: string, state: "tension" | "relaxation", width: number): string =>
  \`https://images.weserv.nl/?url=\${encodeURIComponent(\`cdn.jsdelivr.net/gh/everkinetic/data@main/dist/svg/\${idNum}-\${state}.svg\`)}&w=\${width}&output=webp&q=80\`;

/** BUNDLED 112px thumb (public/illustrations/, committed by the generator) —
 *  zero network requests, instant lists, works offline. */
export const illustrationThumb = (idNum: string): string =>
  \`/illustrations/\${idNum}.webp\`;

const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
let byNorm: Map<string, IllustratedExercise> | null = null;
export const findIllustrated = (name?: string | null): IllustratedExercise | null => {
  if (!name) return null;
  if (!byNorm) {
    byNorm = new Map();
    for (const e of ILLUSTRATED_EXERCISES) byNorm.set(norm(e.title), e);
  }
  return byNorm.get(norm(name)) ?? null;
};
export const normIllustratedName = norm;
`;
writeFileSync("src/data/exercises-illustrated.ts", ts);
console.log(`wrote ${out.length} illustrated exercises`);

// ── Bundle the thumbs: pre-rasterized 112px WebPs into public/illustrations/.
// The list used to fetch each thumb over the network (~300-500ms per edge
// miss; RTT-bound on cellular) — local files make every list instant.
import { mkdirSync, existsSync, statSync } from "node:fs";
const DIR = "public/illustrations";
mkdirSync(DIR, { recursive: true });
const thumbUrl = (idNum) =>
  `https://images.weserv.nl/?url=${encodeURIComponent(`cdn.jsdelivr.net/gh/everkinetic/data@main/dist/svg/${idNum}-tension.svg`)}&w=112&output=webp&q=80`;
const queue = out.filter((e) => {
  const f = `${DIR}/${e.idNum}.webp`;
  return !existsSync(f) || statSync(f).size < 500;
});
console.log(`downloading ${queue.length} thumbs…`);
for (let i = 0; i < queue.length; i += 8) {
  await Promise.all(queue.slice(i, i + 8).map(async (e) => {
    const res = await fetch(thumbUrl(e.idNum));
    if (!res.ok) throw new Error(`thumb ${e.idNum}: HTTP ${res.status}`);
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.length < 500) throw new Error(`thumb ${e.idNum}: suspiciously small (${buf.length}B)`);
    writeFileSync(`${DIR}/${e.idNum}.webp`, buf);
  }));
  if (i % 64 === 0) console.log(`  ${Math.min(i + 8, queue.length)}/${queue.length}`);
}
let ok = 0;
for (const e of out) {
  const f = `${DIR}/${e.idNum}.webp`;
  if (!existsSync(f) || statSync(f).size < 500) throw new Error(`missing/invalid thumb: ${f}`);
  ok++;
}
console.log(`✅ ${ok}/${out.length} bundled thumbs verified in ${DIR}`);
